## How to read the labels

- **Student-free**: Free while you are a verified student. Most of these renew each year.
- **Via college**: Free only if your college has signed up. Ask your library or T&P cell.
- **Discount**: Cheaper for students, but you still pay.
- **Always free**: Free for everyone. No student proof needed.
- **Paused or ended**: Was free once. Check before you plan around it.

## Your verification kit

- **Use your college email if you have one.** Microsoft 365, Notion, Altium and MATLAB check your email domain first, and it is the quickest route everywhere else.
- **No college email? Prepare dated proof.** GitHub accepts a student ID, transcript, enrollment letter or class schedule that shows your name, your college and a current date. SheerID, which Google, Figma and others use, accepts a school ID card with an expiry date, a class schedule, a tuition or registration receipt, a transcript or an official letter. In India a bonafide certificate works as the enrollment letter.
- **Know what usually fails.** Undated ID cards, screenshots of emails, and admission letters for a future term do not prove current enrollment.
- **Match the details.** Type your name and college exactly as they appear on the document, and submit one sharp photo where all three details are readable. A logo alone is not enough.
- **For GitHub, allow location and turn off your VPN.** GitHub checks where you apply from, so applying from campus or on mobile data helps.
- **Do not retry blindly.** Some flows limit attempts. Fix the document first, then contact the provider''s support instead of resubmitting the same file.
- **Claim only what you qualify for.** Providers can deactivate accounts that break program rules, and several student licenses forbid commercial work.

## Code and cloud

Developer tools and cloud credit for verified students.

### GitHub Student Developer Pack

**Label:** Student-free

**What you get.** GitHub Pro features, Codespaces and dozens of partner offers while you stay verified. Benefits usually activate within about 72 hours of approval.

**What you need, and the catch.** Needs a school email on your GitHub account, or a dated ID, transcript, enrollment letter or class schedule showing your name and college. Allow location access and turn off any VPN. In March 2026 students moved to a smaller Copilot Student plan, and GitHub''s FAQ says new Copilot Student activations are paused.

**Official page:** [education.github.com/pack](https://education.github.com/pack)

### JetBrains Student License

**Label:** Student-free

**What you get.** Free educational license for the JetBrains desktop IDEs, including IntelliJ IDEA Ultimate, PyCharm, WebStorm and CLion.

**What you need, and the catch.** Non-commercial learning use only. Renew each year while you study. You can apply with a college email, an ISIC or ITIC card, a GitHub Student Developer Pack account, or a copy of your student ID.

**Official page:** [jetbrains.com/community/education](https://www.jetbrains.com/community/education/#students)

### Azure for Students

**Label:** Student-free

**What you get.** USD 100 of Azure credit valid for 12 months, plus free services. No credit card at sign-up.

**What you need, and the catch.** One Azure for Students subscription per person. The credit cannot be used for Azure Marketplace offers. After 12 months you can sign up again while you are still a student.

**Official page:** [azure.microsoft.com/free/students](https://azure.microsoft.com/en-in/free/students/)

### AWS Student Rewards

**Label:** Student-free

**What you get.** Twelve months of premium AWS Skill Builder, plus AWS credits and a certification exam voucher that you unlock by earning Builder badges.

**What you need, and the catch.** Launched 20 August 2026 on AWS Builder Center. As reported at launch: USD 10 in credits at 7 badges, another USD 20 at 14 badges, and a USD 100 exam voucher at 21. Confirm country eligibility on the page.

**Official page:** [builder.aws.com](https://builder.aws.com/)


