## Common problems and fixes

**School not found or not eligible.** Type the college name exactly as printed on your document. If the dropdown has no match, ask your IT desk whether a student email domain exists.

**My college gives no email.** Use a dated school document. GitHub and SheerID-based offers accept these. Microsoft 365, Notion, MATLAB and Altium rely on your email domain, so ask your college for one.

**Document rejected.** Show your name, the college name and a current date in one sharp photo. A logo alone is not enough. Undated ID cards, email screenshots and future-term admission letters usually fail.

**GitHub location or camera error.** Turn off your VPN, allow location in the browser, and try from a phone on mobile data. Take a live photo instead of uploading an old one.

**Verification limit exceeded.** Stop retrying. Fix the document first, then contact the provider''s support instead of submitting the same file again.

## Frequently asked questions

### Is the GitHub Student Developer Pack free in India?

Yes, for verified students. You add a school email to your GitHub account or upload dated proof such as a student ID, transcript, enrollment letter or class schedule showing your name and college. Benefits typically activate within about 72 hours. As of 3 October 2026, GitHub says new Copilot Student activations are paused.

### Can I get student offers without a college email?

Some of them. GitHub and SheerID-based offers such as Figma and Google AI Plus usually accept dated school documents, and JetBrains accepts an ISIC card or a copy of your student ID. Microsoft 365, Notion, Altium and MATLAB depend on your email domain, so you will need your college to issue one.

### Is Canva Pro free for college students in India?

Not on your own. Canva for Education is free for K-12 teachers and students. College students get Pro only if their college has signed up for Canva for Campus. Otherwise it is Canva Free or a paid plan.

### Is Google AI Pro free for students in India?

No. The original India sign-up for Google AI Pro closed in September 2025. The current India offer is Google AI Plus for 12 months for eligible students aged 18 or older, with a redeem deadline of 31 December 2026. It renews at the paid price afterwards unless you cancel.

### Is Adobe Creative Cloud free for students?

No. Adobe''s student pricing is a discount of about 70 percent. When checked on 3 October 2026, Adobe India listed about ₹638 a month including GST for the first year and about ₹1,516 a month after that.

### Can I use student licenses for freelance or paid work?

Usually not. JetBrains'' educational license is for non-commercial learning, Autodesk''s education access is for educational use only, and Altium''s student license is for personal educational use. Read each license before you take paid work.

### How long do student offers last?

Azure for Students gives 12 months of credit. JetBrains and Autodesk renew every year. Google AI Plus is 12 months free. The GitHub Student Pack typically runs about two years before re-verification. Put the dates in your calendar.

### What should I do if verification keeps failing?

Stop retrying, check that your name, college and a current date are readable in one photo, turn off any VPN for GitHub, and contact the provider''s support. If you have no college email, ask your college for one, because several offers depend on it.

